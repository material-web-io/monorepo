#!/usr/bin/env node
// material3-theme: writes every derived Material 3 token as a CSS custom property, the color
// roles and palettes for a seed color and the spring motion tokens, to the file --out names.
// Published bundled as the package's command; `npm run tokens:generate` runs it for the repo.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { parseArgs } from 'node:util'
import { colorTokens } from './generate-colors.mjs'
import { springTokens } from './generate-springs.mjs'

const usage = `Usage: material3-theme --out <file> [--seed <#RRGGBB>]

Writes the Material 3 color roles, tonal palettes and motion tokens for a seed
color to a CSS file. Import the file after the theme.

  --out <file>       The CSS file to write
  --seed <#RRGGBB>   The seed color (default: #6750A4, the Material 3 baseline)
  -h, --help         Show this help`

// A wrong option ends the run with what is wrong and the usage, not with a stack trace.
function fail(message) {
  console.error(`${message}\n\n${usage}`)
  process.exit(1)
}

let options
try {
  options = parseArgs({
    options: {
      out: { type: 'string' },
      seed: { type: 'string', default: '#6750A4' },
      help: { type: 'boolean', short: 'h' },
    },
  }).values
} catch (error) {
  fail(error.message)
}

if (options.help) {
  console.log(usage)
  process.exit(0)
}
if (!options.out) fail('Expected --out to name the CSS file to write')
if (!/^#[0-9a-f]{6}$/i.test(options.seed)) {
  fail(`Expected --seed to be a #RRGGBB color, got: ${options.seed}`)
}

const colors = colorTokens(options.seed)
const springs = springTokens()
const css = `/* GENERATED by material3-theme from seed ${options.seed.toUpperCase()}.
 * Do not edit by hand; run material3-theme again. */

${colors.css}
${springs.css}`

mkdirSync(dirname(options.out), { recursive: true })
writeFileSync(options.out, css)
console.log(`Wrote ${colors.summary} and ${springs.summary} to ${options.out}`)
